/** 取图片地址；不存在或为空返回 null */
export function iconSrc(slug) {
  if (!slug || typeof slug !== 'string') return null
  return ICON_SRC[slug] || null
}

/** 取中文名，取不到返回空串 */
export function iconLabel(slug) {
  if (!slug || typeof slug !== 'string') return ''
  return ICON_LABEL[slug] || ''
}

